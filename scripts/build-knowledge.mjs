// Builds the AI Recruiter's knowledge file from the same data the website uses,
// so the chatbot and the site can never disagree.
//   Source: src/data/portfolio.ts  ->  Output: worker/src/knowledge.js
// Run: npm run knowledge   (also runs automatically before every site build)
import { rolldown } from 'rolldown';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const tmp = path.resolve('node_modules/.cache/knowledge');
mkdirSync(tmp, { recursive: true });
const bundle = await rolldown({ input: 'src/data/portfolio.ts', logLevel: 'silent' });
await bundle.write({ dir: tmp, format: 'esm', entryFileNames: 'portfolio.mjs' });
const d = await import(pathToFileURL(path.join(tmp, 'portfolio.mjs')).href + `?t=${Date.now()}`);
rmSync(tmp, { recursive: true, force: true });

const { profile, education, experience, projects, achievements, leadership, news, skillCategories, skillEvidence, techStack, yearsExp } = d;
const L = [];
const h = (t) => L.push('', `## ${t}`);
const li = (t) => L.push(`- ${t}`);

L.push(`# ${profile.fullName} — verified portfolio facts`);
L.push(`Source: prashantyadav.tech (generated ${new Date().toISOString().slice(0, 10)}). These are the ONLY facts you may state about him.`);

h('Profile');
li(`Name: ${profile.fullName}`);
li(`Headline: ${profile.seriesTag.toLowerCase().replace(/(^|\s)\S/g, (c) => c.toUpperCase()).replace('Ai', 'AI')}`);
li(`Current role: ${profile.role}`);
li(`Total experience: ${yearsExp}+ years (career started February 2009)`);
li(`Location: ${profile.location}`);
li(`Languages: ${profile.languages}`);
li(`Focus areas: ${profile.focus.join(', ')}`);
li(`Summary: ${profile.intro}`);
li(`More: ${profile.longIntro}`);
li(`In his words: "${profile.quote}"`);

h('Contact and links');
li(`Email: ${profile.email}`);
li(`LinkedIn: ${profile.links.linkedin}`);
if (profile.links.github) li(`GitHub: ${profile.links.github}`);
li(`Resume (PDF): https://prashantyadav.tech${profile.resumePdf}`);
li('Website: https://prashantyadav.tech');

h('Experience (newest first)');
for (const r of experience) {
  L.push('', `### ${r.role} — ${r.company} (${r.place}, ${r.period})`);
  if (r.growth) li(`Growth: ${r.growth}`);
  r.points.forEach(li);
}

h('Education');
education.forEach((e) => li(`${e.degree} — ${e.school}, ${e.place} (${e.period})`));

h('Projects');
for (const p of projects) {
  L.push('', `### ${p.title} — ${p.client}`);
  li(`Type: ${p.genre}`);
  li(`Summary: ${p.logline}`);
  li(`Stack: ${p.stack.join(', ')}`);
  p.build.forEach((b) => li(b));
  if (p.metrics?.length) li(`Metrics: ${p.metrics.map((m) => `${m.value} ${m.label}`).join('; ')}`);
  if (p.github) li(`Code: ${p.github}`);
}

h('Achievements and recognition');
achievements.forEach((a) => li(`${a.title} — ${a.org} (${a.year}): ${a.detail}`));

h('Leadership');
leadership.forEach(li);

h('Speaking and press');
news.forEach((n) => li(`${n.event} — ${n.title}: ${n.detail}`));

h('Skills');
skillCategories.forEach((c) => li(`${c.title} (${c.subtitle}): ${c.skills.map((s) => s.name).join(', ')}`));

h('Where each technology was used');
Object.entries(skillEvidence).forEach(([k, v]) => li(`${k}: ${v.join('; ')}`));

h('Tech stack by layer');
techStack.forEach((t) => li(`${t.layer}: ${t.tools.join(', ')}`));

const text = L.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
mkdirSync('worker/src', { recursive: true });
writeFileSync('worker/src/knowledge.js', `// GENERATED by scripts/build-knowledge.mjs from src/data/portfolio.ts — do not edit by hand.\nexport default ${JSON.stringify(text)};\n`);
console.log(`knowledge: ${text.length} chars, ~${Math.round(text.length / 4)} tokens`);
